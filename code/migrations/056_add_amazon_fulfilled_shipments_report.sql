    `fulfillment-center-id`       VARCHAR(64)  NULL,
    `fulfillment-channel`         VARCHAR(64)  NULL,
    `sales-channel`               VARCHAR(128) NULL,
    PRIMARY KEY (report_task_id, `row_number`),
    INDEX idx_amazon_fulfilled_scope (account_id, seller_id, store_id, `shipment-date`),
    INDEX idx_amazon_fulfilled_order (account_id, seller_id, store_id, `amazon-order-id`),
    INDEX idx_amazon_fulfilled_shipment (account_id, seller_id, store_id, `shipment-id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT 'Amazon FBA fulfilled shipments formal report raw rows including PII';
